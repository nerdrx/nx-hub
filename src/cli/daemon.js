async function cmdDaemon(ctx) {
  const sub = String(ctx.args[0] || "status").toLowerCase();
  if (!SUBS.includes(sub)) {
    throw userError(`unknown daemon command "${ctx.args[0]}"`, "nx daemon run | install | uninstall | status");
  }
  if (sub === "run") return daemonRun(ctx);
  if (sub === "install") return daemonInstall(ctx);
  if (sub === "uninstall") return daemonUninstall(ctx);
  return daemonStatus(ctx);
}

/**
 * `nx daemon run` — the foreground service.
 *
 * stdout is the service's log (journald picks it up) AND the hub's own file log
 * keeps everything, so the CLI's usual muting is lifted here: a daemon that
 * says nothing is a daemon nobody can debug.
 */
async function daemonRun(ctx) {
  const daemon = core(ctx);
  const signals = ctx.signals || ["SIGTERM", "SIGINT"];
  const proc = ctx.process || process;

  // The CLI sets NX_HUB_QUIET=1 for every other command (stdout belongs to the
  // user's pipe). For `daemon run` stdout IS the output — and config.log writes
  // to BOTH stdout and <dataDir>/logs/nx-hub.log, so unmuting it is all it
  // takes to give journald and the file log the same story.
  const restoreQuiet = proc.env.NX_HUB_QUIET;
  delete proc.env.NX_HUB_QUIET;

  // `ctx.log` exists only so a test can watch the lines without writing to the
  // real log file; in life this is config.log and nothing else.
  const say = ctx.log || ((m) => cfg(ctx).log(m));

  let handle;
  try {
    handle = await daemon.start({
      connectorPort: Number(ctx.flags.port) > 0 ? Number(ctx.flags.port) : undefined,
      log: say,
    });
  } catch (e) {
    if (restoreQuiet !== undefined) proc.env.NX_HUB_QUIET = restoreQuiet;
    // A busy port is the expected refusal, not a crash: no stack, exit 2.
    if (ctx.json) ctx.out(JSON.stringify({ ok: false, error: e.message }, null, 2));
    else ctx.err(`${ctx.stErr.danger("nx:")} ${e.message}`);
    return EXIT_FAIL;
  }

  // Every timer inside the daemon is unref'd on purpose (a stray interval must
  // never hold a CLI command open), so the foreground process needs one thing
  // that does keep the loop alive besides the listening sockets.
  const keepAlive = setInterval(() => {}, 1 << 30);

  await new Promise((resolve) => {
    let stopping = false;
    const handlers = [];
    const onSignal = (sig) => async () => {
      if (stopping) {
        // A second signal while we are winding down: the user means it.
        say(`${sig} again — exiting now`);
        clearInterval(keepAlive);
        for (const [s, fn] of handlers) proc.removeListener(s, fn);
        return resolve();
      }
      stopping = true;
      say(`${sig} received — stopping`);
      try {
        await handle.stop();
      } catch (e) {
        say(`stop failed: ${e.message}`);
      }
      clearInterval(keepAlive);
      for (const [s, fn] of handlers) proc.removeListener(s, fn);
      resolve();
    };
    for (const sig of signals) {
      const fn = onSignal(sig);
      handlers.push([sig, fn]);
      proc.on(sig, fn);
    }
  });

  if (restoreQuiet !== undefined) proc.env.NX_HUB_QUIET = restoreQuiet;
  return EXIT_OK;
}

async function daemonInstall(ctx) {
  // eslint-disable-next-line global-require
  const ROOT = require("./runtime").ROOT;
  const result = installUnit({
    binary: process.execPath,
    appDir: ROOT,
    env: ctx.env,
    platform: ctx.platform,
  });

  if (ctx.json) {
    ctx.out(JSON.stringify(Object.assign({ ok: result.action !== "error" && result.action !== "foreign" }, result, { enableCommand: ENABLE_COMMAND }), null, 2));
    return result.action === "error" || result.action === "foreign" ? EXIT_FAIL : EXIT_OK;
  }

  if (result.action === "foreign") {
    ctx.err(`${ctx.stErr.danger("nx:")} ${result.path} was not written by NX Hub — ${result.reason}`);
    ctx.err(ctx.stErr.dim("  move it aside and run `nx daemon install` again"));
    return EXIT_FAIL;
  }
  if (result.action === "error" || result.action === "unsupported") {
    ctx.err(`${ctx.stErr.danger("nx:")} ${result.reason}`);
    return EXIT_FAIL;
  }

  ctx.out(`${ctx.st.cyan("✓")} ${result.action} ${ctx.st.text(result.path)}`);
  if (result.via === "runtime") {
    ctx.out(
      ctx.st.dim("  it points at this runtime directly — `nx shim --force` first if you want it to survive a hub update")
    );
  }
  ctx.out("");
  ctx.out(`  ${ctx.st.muted("enable it with")}`);
  ctx.out(`  ${ctx.st.text(ENABLE_COMMAND)}`);
  ctx.out("");
  ctx.out(`  ${ctx.st.dim("logs: journalctl --user -u nx-hub-daemon -f")}`);
  ctx.out(`  ${ctx.st.dim("the daemon refuses to start while a GUI hub owns the connector port")}`);
  return EXIT_OK;
}

async function daemonUninstall(ctx) {
  const result = removeUnit({ env: ctx.env });
  if (ctx.json) {
    ctx.out(JSON.stringify(Object.assign({ ok: result.action !== "error" && result.action !== "foreign" }, result), null, 2));
    return result.action === "error" || result.action === "foreign" ? EXIT_FAIL : EXIT_OK;
  }
  if (result.action === "foreign") {
    ctx.err(`${ctx.stErr.danger("nx:")} ${result.path} — ${result.reason}`);
    return EXIT_FAIL;
  }
  if (result.action === "error") {
    ctx.err(`${ctx.stErr.danger("nx:")} ${result.reason}`);
    return EXIT_FAIL;
  }
  if (result.action === "absent") {
    ctx.out(`${ctx.st.muted("no unit file to remove")} ${ctx.st.dim(result.path)}`);
    return EXIT_OK;
  }
  ctx.out(`${ctx.st.cyan("✓")} removed ${ctx.st.text(result.path)}`);
  ctx.out(ctx.st.dim("  `systemctl --user daemon-reload` forgets it completely"));
  return EXIT_OK;
}

async function daemonStatus(ctx) {
  const info = await ctx.withStatus("probing…", () => collectStatus(ctx));
  if (ctx.json) {
    ctx.out(JSON.stringify(Object.assign({ ok: true }, info), null, 2));
    return EXIT_OK;
  }
  ctx.out(renderStatus(info, { style: ctx.st }));
  return EXIT_OK;
}

