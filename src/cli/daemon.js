/**
 * Three signals, one verdict:
 *
 *   the port      something is listening on :9021 (bindable = nothing is)
 *   the snapshot  <dataDir>/connector-clients.json, re-stamped by a live hub
 *   the unit      is this machine even set up to run the daemon
 *
 * They can disagree, and when they do that IS the finding: a bound port with a
 * cold snapshot means something owns :9021 that is not a healthy hub, and a
 * fresh snapshot with a free port means a hub died between heartbeats.
 */
function verdict({ listening, snapshot }) {
  if (listening && !snapshot.stale) return "running";
  if (listening) return "stale";
  if (snapshot.exists && !snapshot.stale) return "stale";
  return "stopped";
}

const STATE_TEXT = {
  running: "running",
  stale: "not answering",
  stopped: "stopped",
};

async function collectStatus(ctx, { maxAgeMs = 120000 } = {}) {
  const config = cfg(ctx);
  const daemon = core(ctx);
  const port = Number(ctx.flags.port) > 0 ? Number(ctx.flags.port) : config.NX_CONNECTOR_PORT;
  const listening = await daemon.portBusy(port);
  const snapshot = ipcOf(ctx).readConnectorSnapshot(maxAgeMs);
  const unit = inspectUnit({ env: ctx.env });
  return {
    state: verdict({ listening, snapshot }),
    port,
    host: "127.0.0.1",
    listening,
    clients: snapshot.clients.map((c) => c.app),
    clientCount: snapshot.clients.length,
    ts: snapshot.ts,
    ageMs: snapshot.ageMs,
    snapshotPath: snapshot.path,
    snapshotExists: snapshot.exists,
    dataDir: config.dataDir(),
    logFile: config.logFile(),
    unit: { path: unit.path, exists: unit.exists, ours: unit.ours, state: unit.state },
    enableCommand: ENABLE_COMMAND,
  };
}

/** "8s" / "4m" / "2h" — ISO-independent, locale-independent. */
function ageText(ms) {
  if (!Number.isFinite(ms)) return "never";
  const s = Math.round(ms / 1000);
  if (s < 90) return `${s}s`;
  const m = Math.round(s / 60);
  if (m < 90) return `${m}m`;
  return `${Math.round(m / 60)}h`;
}

function renderStatus(info, { style }) {
  const st = style;
  const glyph = info.state === "running" ? st.cyan("●") : info.state === "stale" ? st.amber("●") : st.muted("○");
  const lines = [`${glyph} ${st.text("nx daemon")} ${st.muted(STATE_TEXT[info.state])}`];
  const row = (label, value) => lines.push(`  ${st.dim(label.padEnd(11))}${value}`);

  row("connector", `${st.text(`${info.host}:${info.port}`)} ${st.dim(info.listening ? "bound" : "free")}`);
  row(
    "roster",
    info.snapshotExists
      ? `${st.text(`${info.clientCount} client${info.clientCount === 1 ? "" : "s"}`)} ${st.dim(`· ${ageText(info.ageMs)} ago`)}${
          info.clientCount ? st.muted(` — ${info.clients.join(", ")}`) : ""
        }`
      : st.muted("never written")
  );
  row("unit", `${st.text(info.unit.path)} ${st.dim(`(${info.unit.state})`)}`);
  if (info.state !== "running") {
    lines.push("");
    if (info.unit.state === "missing") lines.push(`  ${st.dim("install the service with `nx daemon install`")}`);
    else if (info.unit.ours) lines.push(`  ${st.dim(`start it with \`${ENABLE_COMMAND}\``)}`);
  }
  return lines.join("\n");
}

