"use strict";
// `nx daemon` — SPEC v0.10 [daemon]: the hub as a background service.
//
//   nx daemon run                 the hub, foreground, no window (systemd's ExecStart)
//   nx daemon install             write ~/.config/systemd/user/nx-hub-daemon.service
//   nx daemon uninstall           remove it (marker-guarded, like the cli shim)
//   nx daemon status [--json]     is a hub listening, and how fresh is its roster
//
// Everything the daemon actually DOES lives in src/main/daemon.js; this file
// resolves what the user typed, manages one text file, prints, and picks an
// exit code — the same division of labour as ./snapshots.js and ./dev.js.
//
// The unit file is handled exactly like ~/.local/bin/nx (src/cli/shim.js): our
// own marker line is the ONLY thing that authorises a rewrite or a delete, so a
// hand-written nx-hub-daemon.service is never clobbered. And `install` prints
// `systemctl --user enable --now nx-hub-daemon` rather than running it: enabling
// a service is the user's decision, and shelling out to systemctl from a CLI
// that may be running under a different session bus is a good way to be wrong.

const fs = require("fs");
const os = require("os");
const path = require("path");

const shim = require("./shim");

const EXIT_OK = 0;
const EXIT_USER = 1;
const EXIT_FAIL = 2;

const SUBS = ["run", "install", "uninstall", "status"];

/** The one line that says "the hub wrote this" — see shim.js MARKER. */
const MARKER = "# nx-hub-daemon";
const UNIT_NAME = "nx-hub-daemon.service";
const ENABLE_COMMAND = "systemctl --user enable --now nx-hub-daemon";
const REL_ENTRY = path.join("src", "cli", "index.js");

/** Structurally index.js's UserError — see the same note in ./dev.js. */
function userError(message, hint) {
  const e = new Error(message);
  e.name = "UserError";
  e.hint = hint || null;
  e.exitCode = EXIT_USER;
  return e;
}

/** The composition root, lazily — `nx list` must never load the whole hub. */
function core(ctx) {
  // eslint-disable-next-line global-require
  return (ctx && ctx.daemon) || require("../main/daemon");
}

function cfg(ctx) {
  // eslint-disable-next-line global-require
  return (ctx && ctx.config) || require("../main/config");
}

function ipcOf(ctx) {
  // eslint-disable-next-line global-require
  return (ctx && ctx.ipc) || require("../main/ipc");
}

/* ------------------------------------------------------------------ */
/* the unit file                                                       */
/* ------------------------------------------------------------------ */

function unitDir(env = process.env) {
  const base = env.XDG_CONFIG_HOME || path.join(env.HOME || os.homedir(), ".config");
  return path.join(base, "systemd", "user");
}

function unitPath(env = process.env) {
  return path.join(unitDir(env), UNIT_NAME);
}

/**
 * systemd splits ExecStart on whitespace and understands double quotes, so a
 * path with a space in it has to be quoted rather than shell-escaped.
 */
function unitQuote(value) {
  const s = String(value == null ? "" : value);
  if (s && !/[\s"'\\]/.test(s)) return s;
  return `"${s.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
}

/**
 * How systemd should start the daemon.
 *
 * First choice is the shim the hub keeps at ~/.local/bin/nx: it already knows
 * how to find the hub's runtime and it SURVIVES A SELF-UPDATE (the hub rewrites
 * it with the new paths), so a unit pointing at it keeps working across
 * upgrades. Only when there is no shim of ours does the unit bake in this
 * process's own runtime, which is the CLI's usual ELECTRON_RUN_AS_NODE trick
 * written out longhand.
 *
 * @returns {{exec:string, environment:string|null, via:"shim"|"runtime"}}
 */
function execStartFor({ binary, appDir, binDir, env = process.env } = {}) {
  const info = shim.inspect({ binDir, binary, appDir });
  if (info.exists && info.ours) {
    return { exec: `${unitQuote(info.path)} daemon run`, environment: null, via: "shim", shimPath: info.path };
  }
  const entry = path.join(appDir || path.join(__dirname, "..", ".."), REL_ENTRY);
  return {
    exec: `${unitQuote(binary || process.execPath)} ${unitQuote(entry)} daemon run`,
    // ELECTRON_RUN_AS_NODE turns the bundled electron into plain node. Harmless
    // when `binary` is a real node — the variable is simply ignored.
    environment: "ELECTRON_RUN_AS_NODE=1",
    via: "runtime",
    shimPath: info.path,
  };
}

/** The unit text. Pure — tests assert on it directly. */
function renderUnit({ exec, environment } = {}) {
  if (!exec) throw new Error("renderUnit needs an ExecStart command");
  const lines = [
    MARKER,
    "# Generated by NX Hub — `nx daemon install`. Remove it with `nx daemon uninstall`.",
    "",
    "[Unit]",
    "Description=NX Hub daemon (headless installer/updater/bus)",
    "Documentation=https://github.com/nerdrx/nx-hub",
    // The daemon talks to GitHub and to the LAN; starting before the network is
    // up just means the first refresh fails and the loop retries in 6h.
    "After=network-online.target",
    "Wants=network-online.target",
    // A GUI hub taking the connector port back is not a crash loop worth
    // escalating, so the rate limiter is off. It lives in [Unit], not
    // [Service] — systemd moved it there and warns about the old spelling on
    // every daemon-reload (`systemd-analyze verify` says so out loud).
    "StartLimitIntervalSec=0",
    "",
    "[Service]",
    "Type=simple",
  ];
  if (environment) lines.push(`Environment=${environment}`);
  lines.push(
    `ExecStart=${exec}`,
    // SPEC: Restart=on-failure. A clean SIGTERM exits 0 and must STAY stopped —
    // otherwise `systemctl --user stop` would fight the restart policy.
    "Restart=on-failure",
    "RestartSec=10",
    "",
    "[Install]",
    "WantedBy=default.target",
    ""
  );
  return lines.join("\n");
}

/** Was this file written by us? Only our marker authorises a rewrite/removal. */
function isOurs(content) {
  return String(content || "")
    .split("\n")
    .slice(0, 6)
    .some((line) => line.trim() === MARKER);
}

function readIfExists(file) {
  try {
    return fs.readFileSync(file, "utf8");
  } catch (_) {
    return null;
  }
}

/** Current state of the unit file, without touching it. */
function inspectUnit({ env = process.env, wanted = null } = {}) {
  const file = unitPath(env);
  const content = readIfExists(file);
  if (content == null) return { path: file, exists: false, ours: false, state: "missing" };
  if (!isOurs(content)) return { path: file, exists: true, ours: false, state: "foreign" };
  if (wanted) return { path: file, exists: true, ours: true, state: content === wanted ? "current" : "stale" };
  return { path: file, exists: true, ours: true, state: "ours" };
}

/**
 * Write (or refresh) the unit. Never throws.
 * @returns {{action:"written"|"updated"|"unchanged"|"foreign"|"unsupported"|"error", path:string, reason?:string}}
 */
function installUnit({ binary, appDir, binDir, env = process.env, platform = process.platform } = {}) {
  const file = unitPath(env);
  try {
    if (platform !== "linux") {
      return { action: "unsupported", path: file, reason: "systemd user units are a Linux thing" };
    }
    const start = execStartFor({ binary, appDir, binDir, env });
    const wanted = renderUnit(start);
    const current = readIfExists(file);
    if (current != null && !isOurs(current)) {
      return { action: "foreign", path: file, reason: "a unit of that name is already there — left untouched" };
    }
    if (current === wanted) return { action: "unchanged", path: file, via: start.via, exec: start.exec };

    fs.mkdirSync(path.dirname(file), { recursive: true });
    const tmp = `${file}.${process.pid}.tmp`;
    fs.writeFileSync(tmp, wanted, { mode: 0o644 });
    fs.renameSync(tmp, file);
    return { action: current == null ? "written" : "updated", path: file, via: start.via, exec: start.exec };
  } catch (e) {
    return { action: "error", path: file, reason: e.message };
  }
}

/** Remove the unit, but only if it is ours. */
function removeUnit({ env = process.env } = {}) {
  const file = unitPath(env);
  const content = readIfExists(file);
  if (content == null) return { action: "absent", path: file };
  if (!isOurs(content)) return { action: "foreign", path: file, reason: "not written by the hub — left untouched" };
  try {
    fs.rmSync(file, { force: true });
    return { action: "removed", path: file };
  } catch (e) {
    return { action: "error", path: file, reason: e.message };
  }
}

